PATOLOGIE += NEFRO

esc = lambda s: 'null' if s is None else "'" + s.replace("'", "''") + "'"
arr = lambda xs: "'{}'::text[]" if not xs else 'array[' + ', '.join(esc(x) for x in xs) + ']'

solo = NUOVE if '--solo-nuove' in sys.argv else NEFRO if '--solo-nefro' in sys.argv else None
righe = []
for i, p in enumerate(PATOLOGIE):
    if solo is not None and p not in solo:
        continue
    righe.append('(' + ', '.join([
        esc(p['codice']), esc(p['nome']), arr(p['sinonimi']), esc(p['tipo']), esc(p['area']), esc(p['esenzione']),
        'null' if p['orpha'] is None else str(p['orpha']), arr(p['icd']), esc(p['descrizione']), arr(p['allarme']),
        esc(p['diagnosi']), arr(p['follow_up']), esc(p['specialisti']), esc(p['emergenza']), esc(p['note']),
        esc(json.dumps(p['fonti'], ensure_ascii=False)) + '::jsonb', str((i + 1) * 10)]) + ')')

codici = [p['codice'] for p in PATOLOGIE]
assert len(codici) == len(set(codici)), 'codici duplicati'
assert all(p['codice'].isascii() for p in PATOLOGIE)
print('-- %d patologie: %d rare, %d croniche, %d senza esenzione' % (
    len(PATOLOGIE), sum(p['tipo'] == 'rara' for p in PATOLOGIE), sum(p['tipo'] == 'cronica' for p in PATOLOGIE),
    sum(p['esenzione'] is None for p in PATOLOGIE)), file=sys.stderr)
sys.stdout.write(',\n'.join(righe) + ';\n')
